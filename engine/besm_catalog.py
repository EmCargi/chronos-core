# Silver-bracket ladder, monotone in price: an item's guild rank is the
# lowest tier whose quest payout could cover it. Above the A bracket (800 sp
# top) everything is "S"; SS is reserved for explicit GM per-item marking.
RANK_LADDER = (
    ("D", 10),
    ("C", 40),
    ("B", 200),
    ("A", 800),
)


def rank_for_cp(item_cp: int) -> str:
    """Returns the guild rank label for a permanent's item_cp via price."""
    price = fibonacci_price(item_cp)
    for rank, cap in RANK_LADDER:
        if price <= cap:
            return rank
    return "S"


